// Emit the SQL that seeds the two fictional creator-stack demonstrations.
//
// The script never writes to a database itself. It builds each stack document
// through the real validator (`normaliseStack`), so an unsupported instance, an
// undeclared setting or a broken reuse relationship fails here rather than
// appearing as demo data. The output is applied deliberately, by a named
// environment, with the printed Wrangler command.
//
//   node scripts/seed-demo-stacks.mjs                 # writes output/demo-stacks.sql
//   npx wrangler d1 execute app-composer-emdash --local  --file output/demo-stacks.sql
//   npx wrangler d1 execute app-composer-emdash --remote --file output/demo-stacks.sql
//
// Everything here is fiction: no real visitor, contributor, customer or owner
// content appears, and the workspace is named as a demo.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normaliseStack } from '../src/lib/stacks.mjs';

const WORKSPACE = { id: 'workspace-demo-fictional-0001', name: 'Fictional demo workspace' };
const member = 'demo-fictional-creator-0001';

const instance = (id, app, label, caption, extra = {}) => ({
  id,
  app,
  label,
  caption,
  visible: true,
  binding: { mode: 'own', shareOf: null },
  config: {},
  ...extra,
});

