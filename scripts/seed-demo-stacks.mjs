// A demonstration revision that reflects the document: instances plus the reuse
// relationships, so the published number is never a decorative constant.
const revision = stack =>
  stack.document.instances.length +
  stack.document.instances.filter(entry => entry.binding.mode === 'shared').length;

export function seedSQL() {
  const statements = [
    '-- Fictional creator-stack demonstration. Generated by scripts/seed-demo-stacks.mjs.',
    "DELETE FROM creator_stack_publications WHERE stack_id IN (SELECT id FROM creator_stacks WHERE workspace_id = 'workspace-demo-fictional-0001');",
    "DELETE FROM creator_stacks WHERE workspace_id = 'workspace-demo-fictional-0001';",
    `INSERT OR IGNORE INTO creator_workspaces (id, name) VALUES ('${WORKSPACE.id}', '${WORKSPACE.name}');`,
    `INSERT OR IGNORE INTO creator_members (workspace_id, user_id, role) VALUES ('${WORKSPACE.id}', '${member}', 'owner');`,
  ];
  const ids = ['aaaaaaaa-1111-4111-8111-aaaaaaaaaaaa', 'bbbbbbbb-2222-4222-8222-bbbbbbbbbbbb'];
  DEMO_STACKS.forEach((stack, index) => {
    const id = ids[index];
    const json = JSON.stringify(stack.document).replace(/'/g, "''");
    const rev = revision(stack);
    statements.push(
      `INSERT INTO creator_stacks (id, workspace_id, slug, name, status, revision, draft_json, published_json, published_revision, published_at) VALUES ('${id}', '${WORKSPACE.id}', '${stack.slug}', '${stack.document.name}', 'published', ${rev}, '${json}', '${json}', ${rev}, CURRENT_TIMESTAMP);`,
      `INSERT INTO creator_stack_publications (stack_id, revision, document_json) VALUES ('${id}', ${rev}, '${json}');`,
    );
  });
  return statements.join('\n') + '\n';
}

const invoked = Boolean(process.argv[1]) && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) {
  const out = resolve('output/demo-stacks.sql');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, seedSQL());
  for (const stack of DEMO_STACKS) {
    const shared = stack.document.instances.filter(entry => entry.binding.mode === 'shared').length;
    console.log(`${stack.slug}: ${stack.document.instances.length} instance(s), ${shared} shared, theme ${stack.document.theme}`);
  }
  console.log(`\nWrote ${out}. Apply it to a named environment only:`);
  console.log('  npx wrangler d1 execute app-composer-emdash --local  --file output/demo-stacks.sql');
  console.log('  npx wrangler d1 execute app-composer-emdash --remote --file output/demo-stacks.sql');
  console.log('\nPublic addresses:');
  for (const stack of DEMO_STACKS) console.log(`  https://composer.loftwah.com/s/${stack.slug}`);
}
