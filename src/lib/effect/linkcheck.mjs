// Shared, testable presentation helpers for the /effect recorded run.
// The trace itself is produced by Link Check's scripts/effect-demo-fixtures.mjs;
// nothing here invents a result, adds a network call or claims a live check.

export const LINKCHECK_REPOSITORY =
  "https://github.com/loftwah/app-composer-linkcheck";

// Exact Link Check commit that produced docs/effect/run-trace.json.
export const LINKCHECK_COMMIT =
  "9cff98b56bc6e0c6de3d05c1d3094cc76c365358";

export function linkcheckSource(path) {
  return `${LINKCHECK_REPOSITORY}/blob/${LINKCHECK_COMMIT}/${path}`;
}

export function outcomeLine(scenario) {
  if (scenario.outcome.kind === "refused") {
    const reads = scenario.observed.inspectorCalls;
    return `${scenario.outcome.code}. ${reads} read${reads === 1 ? "" : "s"} attempted.`;
  }
  const { report } = scenario.outcome;
  const parts = [`${report.totals.verified} verified`];
  if (report.totals.failed) parts.push(`${report.totals.failed} failed`);
  if (report.totals.uncertain) parts.push(`${report.totals.uncertain} uncertain`);
  parts.push(
    `${report.totals.attempts} attempt${report.totals.attempts === 1 ? "" : "s"}`,
  );
  return `${parts.join(", ")}.`;
}

export function progressLine(scenario, revealed) {
  const total = scenario.phases.length;
  if (revealed === 0) return "Ready to run the recorded check.";
  if (revealed >= total)
    return `Run complete after ${total} steps. ${outcomeLine(scenario)}`;
  const previous = scenario.phases[revealed - 1];
  return `Step ${revealed} of ${total}: ${previous.title}.`;
}

export function copyText(scenario, engine, limits) {
  const lines = [
    "Link Check batch check - recorded demo (synthetic)",
    `Scenario: ${scenario.name}`,
    `Scripted origin: ${scenario.script}`,
    outcomeLine(scenario),
  ];
  if (scenario.outcome.kind === "report") {
    const { report } = scenario.outcome;
    for (const target of report.targets)
      lines.push(
        `- ${target.label}: ${target.status} (${target.code}) after ${target.attempts} attempt${target.attempts === 1 ? "" : "s"}${target.reconciled ? ", reconciled" : ""}`,
      );
    lines.push(`Recovery: ${report.recovery}`);
  } else {
    lines.push(`Refused: ${scenario.outcome.message}`);
  }
  lines.push(
    `Limits: ${limits.targets} targets, ${limits.concurrency} reads at a time, ${limits.attemptsPerTarget} attempts per target, ${limits.retry}, not persisted.`,
    `Source: ${linkcheckSource(engine.module)}`,
    `Tests: ${linkcheckSource(engine.tests)}`,
    "Generated by executing the batch runner with scripted inspectors. No network request; not a live inspection.",
  );
  return lines.join("\n");
}
